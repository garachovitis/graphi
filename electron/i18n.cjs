const DICTS = { el, en }
/** Display names in their own language (the language switch shows both). */
const LANG_NAMES = { el: 'Ελληνικά', en: 'English' }

let lang = 'el'
const setLang = (l) => { if (DICTS[l]) lang = l }
const getLang = () => lang

/** @param {keyof typeof el} key */
function t(key, params) {
  let s = DICTS[lang][key] ?? el[key] ?? key
  if (params) for (const [k, v] of Object.entries(params)) s = s.split(`{${k}}`).join(String(v))
  return s
}

module.exports = { t, setLang, getLang, LANG_NAMES }
